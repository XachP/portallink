// Writes docs/config.js from deploy/*.json so the static dashboard knows every gateway.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, NETWORKS, loadDeployment, LIMITS } from './lib.mjs';

const out = { generated: new Date().toISOString(), limits: LIMITS, networks: {} };
for (const [name, n] of Object.entries(NETWORKS)) {
  if (n.profile !== 'testnet') continue;
  const d = loadDeployment(name);
  out.networks[name] = {
    chainId: n.chainId, rpc: n.rpc, native: n.native, explorer: n.explorer,
    wrappedSymbol: d?.wrappedSymbol ?? null, remote: d?.remote ?? null,
    gateway: d?.gateway ?? null, wrapped: d?.wrapped ?? null, block: d?.block ?? null,
    attesters: d?.attesters ?? [], threshold: d?.threshold ?? 2, txs: d?.txs ?? {},
  };
}
fs.writeFileSync(path.join(ROOT, 'docs', 'config.js'), `// generated by relayer/export-config.mjs - do not edit\nwindow.PORTALLINK = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote docs/config.js');
